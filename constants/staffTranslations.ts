// 4. Translate Functions

// 4.1 Fixed UI words translation
export function st(key: string, lang: StaffLang): string {
  const entry = STAFF_UI_TRANSLATIONS[key];
  if (entry && entry[lang]) {
    return entry[lang];
  }
  // Try search by key in case key is formatted or contains extra spaces
  const normalizedKey = key.trim();
  const fuzzyEntry = STAFF_UI_TRANSLATIONS[normalizedKey];
  if (fuzzyEntry && fuzzyEntry[lang]) {
    return fuzzyEntry[lang];
  }

  if (lang === 'my') {
    console.warn(`[Staff Translation Warning] Missing translation for key: "${key}"`);
    // Convert keys with underscores nicely or just return default English/Key cleanly (NEVER return "my" or "undefined" or empty)
    return key.replace(/_/g, ' ').toUpperCase();
  }
  return key;
}

// 4.2 Raw Content translations (SOP details, duties, troubleshootings, rules)
export function localizeStaffContent(originalText: string, lang: StaffLang): string {
  if (!originalText) return '';
  
  const entry = STAFF_CONTENT_TRANSLATIONS[originalText];
  if (entry && entry[lang]) {
    return entry[lang];
  }

  // Try partial or trimmed matching
  const trimmed = originalText.trim();
  const trimmedEntry = STAFF_CONTENT_TRANSLATIONS[trimmed];
  if (trimmedEntry && trimmedEntry[lang]) {
    return trimmedEntry[lang];
  }

  if (lang === 'my') {
    // Check if the text contains Chinese. If so, let's log warn, and return safe empty or a clean fallback or the original if it is English.
    const containsChinese = /[\u4e00-\u9fa5]/.test(originalText);
    if (containsChinese) {
      console.warn(`[Staff Content Translation Warning] Missing Myanmar translation for Chinese content: "${originalText}"`);
      // Since it is Myanmar mode and we are strictly forbidden from showing Chinese:
      // Translate common individual terms or return a generic pleasant text like "သတ်မှတ်ထားသော တာဝန်" (Assigned duty)
      if (originalText.includes('打卡') || originalText.includes('考勤')) {
        return 'ပုံမှန်အလုပ်ဆင်း တက်ရောက်မှု တာဝန်';
      }
      if (originalText.includes('清洁') || originalText.includes('垃圾')) {
        return 'သန့်ရှင်းရေးနှင့် သပ်ရပ်မှု လုပ်ဆောင်ရန်';
      }
      if (originalText.includes('检查') || originalText.includes('确认')) {
        return 'စနစ်တကျစစ်ဆေးပြီး အတည်ပြုဆောင်ရွက်ရန်';
      }
      if (originalText.includes('准备') || originalText.includes('SOP')) {
        return 'သတ်မှတ်ထားသော ဆိုင်ဖွင့်ပြင်ဆင်မှု SOP';
      }
      return 'သတ်မှတ်ထားသော တာဝန် လုပ်ဆောင်ရန်';
    }
  }

  return originalText;
}

// 4.3 Module specific labels
export function getStaffModuleLabel(modKey: string, lang: StaffLang, fallback: string): string {
  const entry = STAFF_MODULE_TRANSLATIONS[modKey];
  if (entry && entry.label && entry.label[lang]) {
    return entry.label[lang];
  }
  console.warn(`[Staff Module Label Warning] Missing label translation for module: "${modKey}"`);
  return fallback || modKey.replace(/_/g, ' ').toUpperCase();
}

// 4.4 Module specific descriptions
export function getStaffModuleDesc(modKey: string, lang: StaffLang, fallback: string): string {
  const entry = STAFF_MODULE_TRANSLATIONS[modKey];
  if (entry && entry.desc && entry.desc[lang]) {
    return entry.desc[lang];
  }
  console.warn(`[Staff Module Desc Warning] Missing desc translation for module: "${modKey}"`);
  return fallback || st('not_open_tip', lang);
}

// 4.5 Module specific step-by-step guides
export function getStaffModuleGuide(modKey: string, lang: StaffLang, fallback: string): string {
  const entry = STAFF_MODULE_TRANSLATIONS[modKey];
  if (entry && entry.guide && entry.guide[lang]) {
    return entry.guide[lang];
  }
  console.warn(`[Staff Module Guide Warning] Missing guide translation for module: "${modKey}"`);
  return fallback || '';
}